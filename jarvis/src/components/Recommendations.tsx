"use client";
import { Banknote, Eye, PiggyBank, Receipt, Scale, ShieldAlert, Target, TrendingUp } from "lucide-react";
import type { Briefing } from "@/lib/types";

const ICONS: Record<string, typeof Scale> = {
  rebalance: Scale,
  risk: ShieldAlert,
  cash: Banknote,
  debt: Receipt,
  tax: Target,
  savings: PiggyBank,
  opportunity: TrendingUp,
  watch: Eye,
};
const PRIORITY = {
  high: "text-down border-down/40",
  medium: "text-warn border-warn/40",
  low: "text-ink-3 border-line",
};

export function Recommendations({ b }: { b?: Briefing }) {
  const order = { high: 0, medium: 1, low: 2 };
  const recs = [...(b?.recommendations ?? [])].sort((x, y) => order[x.priority] - order[y.priority]);
  return (
    <section className="panel p-5">
      <div className="label">Recommended moves</div>
      <div className="mt-3 space-y-2.5">
        {!b &&
          Array.from({ length: 3 }).map((_, i) => <div key={i} className="skeleton h-20 w-full" />)}
        {recs.map((r, i) => {
          const Icon = ICONS[r.category] ?? Eye;
          return (
            <article key={i} className="rounded-xl border border-line bg-bg/40 p-3.5 transition hover:border-accent/30">
              <div className="flex items-start gap-3">
                <div className="mt-0.5 rounded-lg bg-accent/10 p-2 text-accent">
                  <Icon size={16} aria-hidden />
                </div>
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-2">
                    <h3 className="font-medium text-ink">{r.title}</h3>
                    <span className={`rounded-full border px-1.5 py-px font-mono text-[9px] uppercase tracking-widest ${PRIORITY[r.priority]}`}>
                      {r.priority}
                    </span>
                  </div>
                  <p className="mt-1 text-sm leading-relaxed text-ink-2">{r.detail}</p>
                </div>
              </div>
            </article>
          );
        })}
      </div>
      <p className="mt-3 text-[10px] leading-snug text-ink-3">
        Generated by AI from your account data. Educational only, not personalized financial, tax, or legal advice.
      </p>
    </section>
  );
}
